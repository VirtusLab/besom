package executors

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"

	"github.com/virtuslab/besom/language-host/fsys"
)

const (
	sbt1PluginSource = "/*\n  This file was generated by besom. Do not edit it manually!\n */\n// sbt 1.x flavour\n"
	sbt2PluginSource = "/*\n  This file was generated by besom. Do not edit it manually!\n */\n// sbt 2.x flavour\n"
)

// languagePluginHome fakes the layout of an installed language plugin: one BesomPlugin.scala per sbt line.
func languagePluginHome(t *testing.T) string {
	t.Helper()
	home := t.TempDir()
	for variant, contents := range map[string]string{"sbt1": sbt1PluginSource, "sbt2": sbt2PluginSource} {
		require.NoError(t, os.MkdirAll(filepath.Join(home, variant), 0755))
		require.NoError(t, os.WriteFile(SbtBesomPluginPath(home, variant), []byte(contents), 0644))
	}
	return home
}

// sbtProject fakes a user's sbt project and returns the executor configured for it.
func sbtProject(t *testing.T, home string) (*ScalaExecutor, string) {
	t.Helper()
	projectDir := t.TempDir()
	require.NoError(t, os.WriteFile(filepath.Join(projectDir, "build.sbt"), []byte(""), 0644))

	exec, err := NewScalaExecutor(ScalaExecutorOptions{
		WD:                    fsys.DirFS(projectDir),
		LanguagePluginHomeDir: home,
		UseExecutor:           "sbt",
	})
	require.NoError(t, err)
	require.Equal(t, "sbt", exec.Name)
	return exec, projectDir
}

// Both variants are dropped into the cross-version source directories of the sbt meta-build, so that
// sbt 1.x (Scala 2.12) and sbt 2.x (Scala 3) each compile the one that matches and ignore the other.
func TestSBTSetupProjectWritesBothPluginVariants(t *testing.T) {
	exec, projectDir := sbtProject(t, languagePluginHome(t))
	require.NoError(t, exec.SetupProject())

	sbt1Target := filepath.Join(projectDir, "project", "src", "main", "scala-2.12", "BesomPlugin.scala")
	sbt2Target := filepath.Join(projectDir, "project", "src", "main", "scala-3", "BesomPlugin.scala")

	sbt1Written, err := os.ReadFile(sbt1Target)
	require.NoError(t, err)
	assert.Equal(t, sbt1PluginSource, string(sbt1Written))

	sbt2Written, err := os.ReadFile(sbt2Target)
	require.NoError(t, err)
	assert.Equal(t, sbt2PluginSource, string(sbt2Written))
}

// Projects set up by an older besom carry project/BesomPlugin.scala. sbt compiles it together with the
// cross-version source directories, so it has to go or BesomPlugin ends up defined twice.
func TestSBTSetupProjectRemovesLegacyPlugin(t *testing.T) {
	exec, projectDir := sbtProject(t, languagePluginHome(t))

	legacyPath := filepath.Join(projectDir, "project", "BesomPlugin.scala")
	require.NoError(t, os.MkdirAll(filepath.Dir(legacyPath), 0755))
	require.NoError(t, os.WriteFile(legacyPath, []byte(sbt1PluginSource), 0644))

	require.NoError(t, exec.SetupProject())

	assert.NoFileExists(t, legacyPath)
	assert.FileExists(t, filepath.Join(projectDir, "project", "src", "main", "scala-2.12", "BesomPlugin.scala"))
	assert.FileExists(t, filepath.Join(projectDir, "project", "src", "main", "scala-3", "BesomPlugin.scala"))
}

// A project/BesomPlugin.scala without the besom header belongs to the user, not to us.
func TestSBTSetupProjectKeepsUserAuthoredPlugin(t *testing.T) {
	exec, projectDir := sbtProject(t, languagePluginHome(t))

	userPluginPath := filepath.Join(projectDir, "project", "BesomPlugin.scala")
	userPlugin := "// hand written, nothing to do with besom\nobject BesomPlugin\n"
	require.NoError(t, os.MkdirAll(filepath.Dir(userPluginPath), 0755))
	require.NoError(t, os.WriteFile(userPluginPath, []byte(userPlugin), 0644))

	require.NoError(t, exec.SetupProject())

	kept, err := os.ReadFile(userPluginPath)
	require.NoError(t, err)
	assert.Equal(t, userPlugin, string(kept))
}

// SetupProject runs on every pulumi invocation, so it must not clobber what is already on disk.
func TestSBTSetupProjectDoesNotOverwriteExistingPlugin(t *testing.T) {
	exec, projectDir := sbtProject(t, languagePluginHome(t))

	sbt2Target := filepath.Join(projectDir, "project", "src", "main", "scala-3", "BesomPlugin.scala")
	edited := "// edited by hand\n"
	require.NoError(t, os.MkdirAll(filepath.Dir(sbt2Target), 0755))
	require.NoError(t, os.WriteFile(sbt2Target, []byte(edited), 0644))

	require.NoError(t, exec.SetupProject())

	kept, err := os.ReadFile(sbt2Target)
	require.NoError(t, err)
	assert.Equal(t, edited, string(kept))
}

// removeLegacyBesomPlugin keys off this marker, so every shipped variant has to keep carrying it.
// Without it an upgrade silently leaves the old project/BesomPlugin.scala in place and the meta-build
// ends up with BesomPlugin defined twice. Doubles as a check that the resources sit where we expect.
func TestShippedBesomPluginsCarryGeneratedMarker(t *testing.T) {
	for _, v := range sbtBesomPluginVariants {
		shipped := filepath.Join("..", "..", "resources", v.variant, "BesomPlugin.scala")
		contents, err := os.ReadFile(shipped)
		require.NoError(t, err)
		assert.Contains(t, string(contents), besomPluginGeneratedMarker, "variant %s", v.variant)
	}
}

// --numeric-version is sbt 1.x only; on sbt 2.x it is ignored and sbt drops into an interactive shell.
func TestSBTVersionArgsWorkOnBothSbtLines(t *testing.T) {
	exec, _ := sbtProject(t, languagePluginHome(t))
	assert.Equal(t, []string{"--script-version"}, exec.VersionArgs)
}
